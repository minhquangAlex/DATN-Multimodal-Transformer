"""Kaggle extraction: audit real images, never encode a substitute black image."""
import argparse
import importlib.metadata
from pathlib import Path
import pandas as pd
import torch
from PIL import Image, UnidentifiedImageError
from src.config import file_sha256, write_json
from src.features.verify_embeddings import verify_stage2_embeddings


def image_path(images_dir, article_id):
    return Path(images_dir) / article_id[:3] / f'{article_id}.jpg'


def audit_images(selected, images_dir):
    if not Path(images_dir).is_dir():
        raise FileNotFoundError(f'Image directory does not exist: {images_dir}')
    records = []
    for row in selected.itertuples():
        path = image_path(images_dir, row.article_id)
        status = 'ok'
        try:
            with Image.open(path) as source:
                source.convert('RGB').load()
        except FileNotFoundError:
            status = 'missing'
        except (OSError, UnidentifiedImageError):
            status = 'unreadable'
        records.append({'article_id': row.article_id, 'image_available': status == 'ok',
                        'image_status': status, 'text_available': bool(row.text_available)})
    return pd.DataFrame(records)


def extract_embeddings(selected_articles_path, images_dir, output_dir='embeddings/v2', batch_size=64,
                       max_missing_image_fraction=0.0, image_revision='main', text_revision='main'):
    from transformers import CLIPVisionModel, CLIPImageProcessor
    from sentence_transformers import SentenceTransformer

    output = Path(output_dir)
    output.mkdir(parents=True, exist_ok=True)
    if batch_size < 1 or not 0 <= max_missing_image_fraction < 1:
        raise ValueError('Invalid batch size or missing-image threshold')
    selected = pd.read_csv(selected_articles_path, dtype={'article_id': str})
    required = {'article_id', 'text_for_embedding', 'text_available'}
    if not required.issubset(selected.columns):
        raise ValueError('Use selected_articles.csv generated by stage 1 v2')
    if selected.empty or selected.article_id.isna().any() or selected.article_id.duplicated().any():
        raise ValueError('Invalid article IDs')
    if not selected.article_id.str.fullmatch(r'\d{10}').all():
        raise ValueError('Article IDs must contain exactly 10 digits')
    if selected.text_available.isna().any() or not selected.text_available.isin([True, False]).all():
        raise ValueError('Invalid text availability flags')
    audit = audit_images(selected, images_dir)
    audit.to_csv(output / 'availability.csv', index=False)
    missing_fraction = float((~audit.image_available).mean())
    write_json(output / 'image_audit.json', {'counts': audit.image_status.value_counts().to_dict(),
                                           'missing_fraction': missing_fraction})
    if missing_fraction > max_missing_image_fraction or not audit.image_available.any():
        raise ValueError(f'Image audit failed: {missing_fraction:.2%} unavailable; check images_dir and image_audit.json')
    device = 'cuda' if torch.cuda.is_available() else 'cpu'
    print(f'Extraction device: {device}; real images: {audit.image_available.sum()}/{len(audit)}', flush=True)
    image_name = 'openai/clip-vit-base-patch32'
    text_name = 'sentence-transformers/all-MiniLM-L6-v2'
    vision = CLIPVisionModel.from_pretrained(image_name, revision=image_revision).to(device).eval()
    processor = CLIPImageProcessor.from_pretrained(image_name, revision=image_revision, use_fast=False)
    image_dim = vision.config.hidden_size
    image_dict = {key: torch.zeros(image_dim) for key in selected.article_id}
    available_ids = audit.loc[audit.image_available, 'article_id'].tolist()
    with torch.inference_mode():
        for start in range(0, len(available_ids), batch_size):
            keys = available_ids[start:start + batch_size]
            images = []
            for key in keys:
                with Image.open(image_path(images_dir, key)) as source:
                    images.append(source.convert('RGB'))
            pixels = processor(images=images, return_tensors='pt')['pixel_values'].to(device)
            vectors = torch.nn.functional.normalize(vision(pixel_values=pixels).pooler_output.float(), dim=-1).cpu()
            image_dict.update(zip(keys, vectors.unbind()))
            print(f'Image embeddings: {min(start + batch_size, len(available_ids))}/{len(available_ids)}', flush=True)
    resolved_image_revision = getattr(vision.config, '_commit_hash', None)
    del vision
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    language = SentenceTransformer(text_name, revision=text_revision, device=device)
    text_dim = language.get_sentence_embedding_dimension()
    text_dict = {key: torch.zeros(text_dim) for key in selected.article_id}
    valid_text = selected.loc[selected.text_available.eq(True)]
    if valid_text.text_for_embedding.isna().any():
        raise ValueError('Available text cannot be empty')
    if len(valid_text):
        vectors = language.encode(valid_text.text_for_embedding.tolist(), batch_size=batch_size,
                                  normalize_embeddings=True, convert_to_tensor=True, show_progress_bar=True).cpu()
        text_dict.update(zip(valid_text.article_id, vectors.unbind()))
    img_path, txt_path = output / 'image/image_embeddings.pt', output / 'text/text_embeddings.pt'
    img_path.parent.mkdir(parents=True, exist_ok=True)
    txt_path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(image_dict, img_path)
    torch.save(text_dict, txt_path)
    write_json(output / 'metadata.json', {
        'schema_version': 2, 'validation': 'pending', 'article_count': len(selected),
        'selected_articles_sha256': file_sha256(selected_articles_path),
        'image_sha256': file_sha256(img_path), 'text_sha256': file_sha256(txt_path),
        'availability_sha256': file_sha256(output / 'availability.csv'),
        'image_dim': image_dim, 'text_dim': text_dim, 'image_model': image_name, 'text_model': text_name,
        'image_revision_requested': image_revision, 'image_revision_resolved': resolved_image_revision,
        'text_revision_requested': text_revision,
        'text_revision_resolved': getattr(language[0].auto_model.config, '_commit_hash', None),
        'image_feature': 'L2-normalized vision pooler_output', 'text_feature': 'L2-normalized sentence embedding',
        'packages': {name: importlib.metadata.version(name) for name in ['torch', 'transformers', 'sentence-transformers', 'Pillow']},
        'device': device,
    })
    return verify_stage2_embeddings(selected_articles_path, img_path, txt_path, output / 'metadata.json',
                                    require_full=max_missing_image_fraction == 0)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--selected-articles-path', required=True)
    parser.add_argument('--images-dir', required=True)
    parser.add_argument('--output-dir', default='embeddings/v2')
    parser.add_argument('--batch-size', type=int, default=64)
    parser.add_argument('--max-missing-image-fraction', type=float, default=0.0)
    extract_embeddings(**vars(parser.parse_args()))
